#!/usr/bin/env python3
"""Write a ready-to-run LAMMPS+MACE relax input."""
from __future__ import annotations

import argparse
from pathlib import Path

TEMPLATE = """# Generated by write_lammps_in.py
units           metal
atom_style      atomic
boundary        p p p

read_data       {data_file}

pair_style      mace no_domain_decomposition
pair_coeff      * * {mace_model} {species}

neighbor        1.0 bin
neigh_modify    delay 0 every 1 check yes

fix_modify     box/relax iso 0.0 vmax 0.001
min_style       cg
minimize        1.0e-6 1.0e-8 10000 100000

variable        e equal pe
print           "FINAL_PE ${{e}}"

write_data      {data_out}
write_dump      all custom {dump_out} id type x y z modify element {species}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description="Write LAMMPS MACE relax input")
    parser.add_argument("--mace-model", type=Path, required=True)
    parser.add_argument("--type-order", nargs="+", required=True)
    parser.add_argument("--data-file", type=Path, default=Path("data.sqs"))
    parser.add_argument("--out", type=Path, default=Path("in.relax.generated"))
    parser.add_argument("--data-out", type=Path, default=Path("data.sqs.relaxed"))
    parser.add_argument("--dump-out", type=Path, default=Path("dump.relaxed.xyz"))
    args = parser.parse_args()

    args.out.write_text(
        TEMPLATE.format(
            data_file=args.data_file.as_posix(),
            mace_model=args.mace_model.resolve().as_posix(),
            species=" ".join(args.type_order),
            data_out=args.data_out.as_posix(),
            dump_out=args.dump_out.as_posix(),
        ),
        encoding="utf-8",
    )
    print(f"wrote {args.out.resolve()}")


if __name__ == "__main__":
    main()
